//! `.option` names with value kinds, defaults and descriptions.

use super::{Named, Status, Usage, find_named};

/// Whether an option is a flag, takes a value, or both.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OptionValue {
    /// Bare name sets it to 1 (`.option post`).
    Flag,
    /// Requires `name=value`.
    Value,
    /// Either form is accepted.
    FlagOrValue,
}

/// Static description of one `.option`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OptionSpec {
    /// Lowercase option name.
    pub name: &'static str,
    /// Alternative spellings.
    pub aliases: &'static [&'static str],
    /// Accepted value form.
    pub value: OptionValue,
    /// Documented default, if any.
    pub default: Option<&'static str>,
    /// One-line description.
    pub description: &'static str,
    /// How common the option is.
    pub usage: Usage,
    /// Support status (obsolete options are flagged).
    pub status: Status,
}

impl Named for OptionSpec {
    fn name(&self) -> &'static str {
        self.name
    }

    fn aliases(&self) -> &'static [&'static str] {
        self.aliases
    }
}

