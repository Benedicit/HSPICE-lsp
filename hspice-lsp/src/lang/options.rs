/// Looks up an option by name or alias (case-insensitive).
///
/// # Arguments
/// * `name` - option name as written
pub fn find_option(name: &str) -> Option<&'static OptionSpec> {
    find_named(OPTIONS, name)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn finds_by_name_alias_and_case() {
        assert_eq!(
            find_option("POST").map(|o| o.value),
            Some(OptionValue::FlagOrValue)
        );
        assert_eq!(find_option("Autost").map(|o| o.name), Some("autostop"));
        assert_eq!(find_option("ABSV").map(|o| o.name), Some("vntol"));
        assert_eq!(find_option("itl3").map(|o| o.name), Some("imin"));
        assert_eq!(
            find_option("reltol").map(|o| o.value),
            Some(OptionValue::Value)
        );
        assert_eq!(
            find_option("probe").map(|o| o.value),
            Some(OptionValue::FlagOrValue)
        );
        assert!(find_option("RUN_LVL").is_none());
        assert_eq!(find_option("absi").map(|o| o.name), Some("absi"));
        assert_eq!(find_option("posttop").map(|o| o.name), Some("posttop"));
        assert_eq!(find_option("hb_maxiter").map(|o| o.name), Some("hbmaxiter"));
        assert!(find_option("nonsense").is_none());
    }

    #[test]
    fn obsolete_options_are_flagged() {
        assert_eq!(
            find_option("zuken").map(|o| o.status),
            Some(Status::Obsolete)
        );
        assert_eq!(
            find_option("post").map(|o| o.status),
            Some(Status::Supported)
        );
    }

    #[test]
    fn table_invariants() {
        let names: Vec<&str> = OPTIONS
            .iter()
            .flat_map(|o| std::iter::once(o.name).chain(o.aliases.iter().copied()))
            .collect();
        assert_eq!(names.len(), names.iter().collect::<HashSet<_>>().len());
        assert!(names.iter().all(|n| *n == n.to_ascii_lowercase()));
        assert!(OPTIONS.iter().all(|o| !o.description.is_empty()));
        assert!(OPTIONS.len() >= 350);
    }
}
